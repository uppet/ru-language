"""Opt-in integration contracts and ordinary C/JS output snapshots."""
import hashlib
import json
from pathlib import Path
import tempfile
import unittest
from unittest.mock import patch

from rulang import __version__
from rulang.cli import build, make_parser
from rulang.compiler import Compiler
from rulang.frontend import RuError, parse
from rulang.js_compiler import JSCompiler


HEADERS = {
    Compiler: '/* Generated by ru {version}. Standalone C99; source AST is not embedded. */',
    JSCompiler: '// Generated by ru {version}. Standalone Node.js; no source AST.',
}


def historical_output_bytes(generated, compiler):
    """Normalize only the versioned banner; keep the frozen body byte-for-byte."""
    header, newline, body = generated.partition('\n')
    expected = HEADERS[compiler].format(version=__version__)
    if not newline or header != expected:
        raise ValueError('generated header must state the exact current version')
    return (HEADERS[compiler].format(version='0.23.0') + newline + body).encode()


class MiIntegration(unittest.TestCase):
    def test_default_generated_outputs_match_baseline(self):
        fixture = json.loads((Path(__file__).parent / 'fixtures/mi-default.json').read_text(encoding='utf-8'))
        actual = [hashlib.sha256(historical_output_bytes(cls(parse(source), '/fixed/example.ru').compile(), cls)).hexdigest()
                  for source in fixture['sources'] for cls in (Compiler, JSCompiler)]
        self.assertEqual(actual, fixture['sha256'])


    def test_historical_hash_normalization_preserves_body_and_rejects_wrong_banner(self):
        body = 'literal version ' + __version__ + '\nunchanged body\n'
        for cls, template in HEADERS.items():
            header = template.format(version=__version__)
            generated = header + '\n' + body
            expected = (template.format(version='0.23.0') + '\n' + body).encode()
            self.assertEqual(historical_output_bytes(generated, cls), expected)
            self.assertNotEqual(hashlib.sha256(historical_output_bytes(generated + 'body mutation', cls)).digest(),
                                hashlib.sha256(expected).digest())
            for invalid in (generated.replace(header, template.format(version='0.0.0'), 1),
                            'unexpected banner\n' + body, header):
                with self.subTest(compiler=cls.__name__, invalid=invalid), self.assertRaises(ValueError):
                    historical_output_bytes(invalid, cls)

    def test_manifest_cannot_be_output_or_emit_c(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            entry = root / 'main.ru'; entry.write_text('显 1.', encoding='utf-8')
            manifest = root / 'manifest.json'
            original = b'{"version":1,"functions":[]}'
            manifest.write_bytes(original)
            output = root / 'program'; output.write_bytes(b'previous binary')
            for destination in ('output', 'emit_c'):
                for alias in (manifest, root / '.' / 'manifest.json'):
                    with self.subTest(destination=destination, alias=str(alias)):
                        with patch('rulang.cli.subprocess.run') as invoked:
                            with self.assertRaises(RuError):
                                build(parse('显 1.'), entry, alias if destination == 'output' else output,
                                      emit_c=alias if destination == 'emit_c' else None,
                                      mi_manifest=manifest)
                            invoked.assert_not_called()
                        self.assertEqual(manifest.read_bytes(), original)
                        self.assertEqual(output.read_bytes(), b'previous binary')

    def test_non_c_manifest_is_rejected_before_tools(self):
        with patch('rulang.cli.subprocess.run') as invoked:
            with self.assertRaisesRegex(RuError, '仅支持 C'):
                build(parse('显 1.'), 'main.ru', 'program.js', target='js', mi_manifest='manifest.json')
            invoked.assert_not_called()

    def test_llvm_is_explicit_and_c_remains_default(self):
        parser = make_parser()
        options = {action.dest: action for action in parser._subparsers._group_actions[0].choices['build']._actions}
        self.assertEqual(tuple(options['target'].choices), ('c', 'js', 'llvm', 'ui'))
        self.assertEqual(options['target'].default, 'c')
        self.assertIn('llvm_clang', options)
        self.assertIn('emit_llvm', options)
        with self.assertRaises(RuError):
            Compiler(parse('显 1.'), mi_backend='llvm')

    def test_default_c_build_does_not_require_llvm_tools(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            entry = root / 'main.ru'; entry.write_text('显 1.', encoding='utf-8')
            def compile_stub(command, **kwargs):
                Path(command[command.index('-o') + 1]).write_bytes(b'compiled C')
                from subprocess import CompletedProcess
                return CompletedProcess(command, 0, '', '')
            with patch('rulang.llvm_toolchain.LLVMToolchain', side_effect=AssertionError('unexpected LLVM lookup')):
                with patch('rulang.cli.subprocess.run', side_effect=compile_stub) as invoked:
                    output, _ = build(parse('显 1.'), entry, root / 'program', cc='gcc')
                    self.assertEqual(output.read_bytes(), b'compiled C')
                    self.assertEqual(invoked.call_count, 1)

    def test_explicit_llvm_build_dispatches_to_llvm_tools(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            entry = root / 'main.ru'; entry.write_text('显 1.', encoding='utf-8')
            with patch('rulang.llvm_toolchain.build_llvm', return_value=('artifact', 'LLVM 14')) as llvm:
                self.assertEqual(build(parse('显 1.'), entry, root / 'program', target='llvm'),
                                 ('artifact', 'LLVM 14'))
                llvm.assert_called_once()
